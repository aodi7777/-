const nodes = document.querySelectorAll(".node");
const detailIndex = document.querySelector("#detail-index");
const detailPhase = document.querySelector("#detail-phase");
const detailTitle = document.querySelector("#detail-title");
const detailPurpose = document.querySelector("#detail-purpose");
const detailActions = document.querySelector("#detail-actions");
const detailDeliverables = document.querySelector("#detail-deliverables");
const detailMetric = document.querySelector("#detail-metric");

function renderList(target, items) {
  target.replaceChildren(
    ...items.map((item) => {
      const li = document.createElement("li");
      li.textContent = item;
      return li;
    })
  );
}

function selectModule(id) {
  const item = modules[id] ?? modules.vision;
  detailIndex.textContent = item.index;
  detailPhase.textContent = item.phase;
  detailTitle.textContent = item.title;
  detailPurpose.textContent = item.purpose;
  renderList(detailActions, item.actions);
  renderList(detailDeliverables, item.deliverables);
  detailMetric.textContent = item.metric;

  nodes.forEach((node) => {
    node.classList.toggle("is-active", node.dataset.id === id);
  });
}

nodes.forEach((node) => {
  node.addEventListener("click", () => selectModule(node.dataset.id));
});

selectModule("vision");
